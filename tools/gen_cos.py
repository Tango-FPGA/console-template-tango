"""gen_cos.py -- rtl/template_cos.vh: the Template core's quarter-cosine table as a logic ROM function.
q[i] = round(127 cos((i + 0.5) pi / 512)), i = 0..255 (our own table; MiSTer's rtl/cos.sv plays the same role).
usage: gen_cos.py   (rewrites rtl/template_cos.vh)"""
import math, os
Q = [max(0, min(127, round(127 * math.cos((i + 0.5) * math.pi / 512)))) for i in range(256)]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'rtl', 'template_cos.vh')
s = '// SPDX-License-Identifier: GPL-2.0-or-later\n// Copyright (c) 2026 the Tango authors\n'
s += '// GENERATED by tools/gen_cos.py -- do not edit.  q[i] = round(127 cos((i + 0.5) pi / 512))\n'
s += 'function [6:0] template_qcos(input [7:0] i);\n    case (i)\n'
for i, v in enumerate(Q): s += f"        8'd{i}: template_qcos = 7'd{v};\n"
s += "        default: template_qcos = 7'd0;\n    endcase\nendfunction\n"
open(out, 'w').write(s); print('wrote', out)
